#!/usr/bin/env python3
"""Standalone tool: build the HTML job-opportunities report from matches JSON.

Reads the output of tools/match_vacancies.py and writes an HTML report
(green/yellow/red fit badges, above-threshold table, below-threshold list)
to profiles/<profile>/report_<DATE>.html by default.

Usage:
    uv run python tools/build_report.py \\
        --profile <name> \\
        --matches-file /tmp/<name>_matches.json

Options:
    --min-fit N         Override min_fit_percentage (default: from config.yaml, fallback 30)
    --date YYYY-MM-DD   Report date in title/filename (default: today)
    --output PATH       Override output file (default: profiles/<profile>/report_<date>.html)
    --print-summary     Also print "[fit%] title at company" lines to stdout

Prints the output path on success.
"""

import argparse
import html
import json
import sys
from datetime import date as _date
from pathlib import Path

from gmail_summarizer.config import load_config


def color(p: int) -> str:
    if p >= 70:
        return "#34a853"
    if p >= 50:
        return "#fbbc04"
    return "#ea4335"


def esc(s: str | None) -> str:
    return html.escape(s or "")


def render(matches: list[dict], min_fit: int, report_date: str) -> tuple[str, list[dict], list[dict]]:
    above = [m for m in matches if (m.get("fit_percentage") or 0) >= min_fit]
    below = [m for m in matches if (m.get("fit_percentage") or 0) < min_fit and m.get("fit_percentage") is not None]

    rows = []
    for i, m in enumerate(above, 1):
        matches_str = ", ".join(esc(x) for x in m.get("key_matches", [])) or "—"
        gaps_str = ", ".join(esc(x) for x in m.get("gaps", [])) or "—"
        rows.append(f"""            <tr>
                <td style="padding:12px;border-bottom:1px solid #eee;">{i}</td>
                <td style="padding:12px;border-bottom:1px solid #eee;">
                    <a href="{esc(m['url'])}" style="color:#1a73e8;text-decoration:none;">
                        <strong>{esc(m.get('title'))}</strong>
                    </a><br>
                    <span style="color:#666;">{esc(m.get('company'))} &middot; {esc(m.get('location'))}</span>
                </td>
                <td style="padding:12px;border-bottom:1px solid #eee;text-align:center;">
                    <span style="background:{color(m['fit_percentage'])};color:#fff;padding:4px 10px;border-radius:12px;font-weight:bold;">
                        {m['fit_percentage']}%
                    </span>
                </td>
                <td style="padding:12px;border-bottom:1px solid #eee;">{esc(m.get('summary'))}</td>
                <td style="padding:12px;border-bottom:1px solid #eee;font-size:0.9em;">
                    <strong>Matches:</strong> {matches_str}<br>
                    <strong>Gaps:</strong> {gaps_str}
                </td>
            </tr>""")

    below_rows = [
        f'<li><strong>[{m["fit_percentage"]}%]</strong> '
        f'<a href="{esc(m["url"])}" style="color:#1a73e8;text-decoration:none;">{esc(m.get("title"))}</a> '
        f'&middot; {esc(m.get("company"))} &mdash; <em>{esc(m.get("summary"))}</em></li>'
        for m in below
    ]
    below_block = ""
    if below_rows:
        below_block = f"""
    <h3 style="color:#666;margin-top:32px;">Below threshold ({min_fit}%) — {len(below)} listings</h3>
    <ul style="font-size:0.9em;color:#555;line-height:1.6;">
        {"".join(below_rows)}
    </ul>"""

    doc = f"""<html>
<body style="font-family:Arial,sans-serif;color:#333;max-width:900px;margin:auto;">
    <h2 style="color:#1a73e8;">Job Opportunities Report — {report_date}</h2>
    <p>Found <strong>{len(above)}</strong> matching vacancies, ranked by fit percentage. ({len(matches)} total scored, {len(below)} below {min_fit}% threshold.)</p>
    <table style="width:100%;border-collapse:collapse;">
        <thead>
            <tr style="background:#f5f5f5;">
                <th style="padding:12px;text-align:left;">#</th>
                <th style="padding:12px;text-align:left;">Position</th>
                <th style="padding:12px;text-align:center;">Fit</th>
                <th style="padding:12px;text-align:left;">Summary</th>
                <th style="padding:12px;text-align:left;">Details</th>
            </tr>
        </thead>
        <tbody>
{chr(10).join(rows) if rows else '            <tr><td colspan="5" style="padding:24px;text-align:center;color:#999;">No matches above threshold.</td></tr>'}
        </tbody>
    </table>
{below_block}
    <p style="color:#999;font-size:0.85em;margin-top:24px;">
        Generated by AI Gmail Summarizer
    </p>
</body>
</html>"""
    return doc, above, below


def main():
    parser = argparse.ArgumentParser(description="Build HTML job-opportunities report from matches JSON")
    parser.add_argument("--profile", required=True, help="Profile name (directory under profiles/)")
    parser.add_argument("--matches-file", required=True, help="JSON file from tools/match_vacancies.py")
    parser.add_argument("--min-fit", type=int, help="Override min_fit_percentage (default: from config.yaml)")
    parser.add_argument("--date", help="Report date YYYY-MM-DD (default: today)")
    parser.add_argument("--output", help="Output HTML path (default: profiles/<profile>/report_<date>.html)")
    parser.add_argument("--print-summary", action="store_true", help="Print '[fit%%] title at company' lines to stdout")
    args = parser.parse_args()

    matches = json.loads(Path(args.matches_file).read_text(encoding="utf-8"))
    if not isinstance(matches, list):
        print("Error: matches file must be a JSON list", file=sys.stderr)
        sys.exit(2)

    config = load_config(args.profile)
    min_fit = args.min_fit if args.min_fit is not None else config.min_fit_percentage
    report_date = args.date or _date.today().isoformat()
    out_path = Path(args.output) if args.output else Path(f"profiles/{args.profile}/report_{report_date}.html")

    doc, above, below = render(matches, min_fit, report_date)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(doc, encoding="utf-8")
    print(str(out_path))

    if args.print_summary:
        print(f"\nJob Opportunities Report — {report_date}", file=sys.stderr)
        for i, m in enumerate(above, 1):
            print(f"  {i}. [{m['fit_percentage']}%] {m.get('title')} at {m.get('company')}", file=sys.stderr)
        print(f"\n{len(above)} above {min_fit}%, {len(below)} below.", file=sys.stderr)


if __name__ == "__main__":
    main()
